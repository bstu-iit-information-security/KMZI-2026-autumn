"""### 1.4. Многоразрядный сумматор (2, 3, 4 разряда) и проверка всех 256 пар для 4 бит"""

import pandas as pd
from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator

def append_full_adder(qc: QuantumCircuit, a_q: int, b_q: int, x_q: int, s_q: int, c_q: int) -> None:
    """
    Добавляет в схему qc полный сумматор на кубитах:
      a_q, b_q  — разряды слагаемых
      x_q       — входной перенос (carry in)
      s_q       — кубит суммы (изначально |0>)
      c_q       — кубит выходного переноса (изначально |0>)
    """
    # S = a_q XOR b_q XOR x_q
    qc.cx(a_q, s_q)
    qc.cx(b_q, s_q)
    qc.cx(x_q, s_q)

    # C = (a_q AND b_q) OR (x_q AND (a_q XOR b_q))
    qc.cx(a_q, b_q)          # b_q временно хранит a_q XOR b_q
    qc.ccx(x_q, b_q, c_q)   # c_q ^= x_q AND (a_q XOR b_q)
    qc.cx(a_q, b_q)         # восстанавливаем b_q
    qc.ccx(a_q, b_q, c_q)   # c_q ^= a_q AND b_q

def build_ripple_carry_adder(n_bits: int, a_val: int = 0, b_val: int = 0, measure: bool = True) -> QuantumCircuit:
    """
    n-разрядный сумматор с цепочкой переноса (выдаёт (n_bits + 1)-битный результат).
    Кубиты:
      0 .. n_bits-1             -> биты числа a (младший бит в 0)
      n_bits .. 2*n_bits-1      -> биты числа b
      2*n_bits .. 3*n_bits-1    -> биты суммы s_0 .. s_{n_bits-1}
      3*n_bits                  -> входной перенос c_in = |0> (используется для промежуточных переносов c_1..c_{n_bits-1})
      3*n_bits+1 .. 4*n_bits    -> кубиты переносов для каждого разряда
    """
    # Простая и прозрачная раскладка регистров:
    # a: n_bits кубитов [0 .. n_bits-1]
    # b: n_bits кубитов [n_bits .. 2*n_bits-1]
    # s: n_bits кубитов [2*n_bits .. 3*n_bits-1]
    # carry: n_bits + 1 кубитов [3*n_bits .. 4*n_bits], где carry[0] = 0 (входной перенос),
    #        carry[i+1] — выходной перенос после i-го разряда, а старший бит результата — carry[n_bits]
    total_qubits = 4 * n_bits + 1
    qc = QuantumCircuit(total_qubits)

    for bit in range(n_bits):
        if (a_val >> bit) & 1:
            qc.x(bit)
        if (b_val >> bit) & 1:
            qc.x(n_bits + bit)

    for bit in range(n_bits):
        a_q = bit
        b_q = n_bits + bit
        x_q = 3 * n_bits + bit
        s_q = 2 * n_bits + bit
        c_q = 3 * n_bits + bit + 1
        append_full_adder(qc, a_q, b_q, x_q, s_q, c_q)

    if measure:
        qc.measure_all()
    return qc

def adder_metrics(n_bits: int) -> dict:
    qc = build_ripple_carry_adder(n_bits, 0, 0, measure=False)
    ops = qc.count_ops()
    return {
        "Разрядов (n)": n_bits,
        "Кубитов": qc.num_qubits,
        "CX": ops.get("cx", 0),
        "CCX": ops.get("ccx", 0),
        "Глубина (depth)": qc.depth(),
    }

