def full_adder_circuit(a: int, b: int, x: int, measure: bool = True) -> QuantumCircuit:
    # Кубиты: 0 -> A, 1 -> B, 2 -> X (carry in), 3 -> S (sum), 4 -> C (carry out)
    qc = QuantumCircuit(5)
    if a:
        qc.x(0)
    if b:
        qc.x(1)
    if x:
        qc.x(2)

    # S = A XOR B XOR X
    qc.cx(0, 3)
    qc.cx(1, 3)
    qc.cx(2, 3)

    # C = (A AND B) OR (X AND (A XOR B))
    # Сначала получаем A XOR B в кубите 1 (временно)
    qc.cx(0, 1)
    qc.ccx(2, 1, 4)   # X AND (A XOR B) -> C
    qc.cx(0, 1)       # возвращаем B в исходное состояние
    qc.ccx(0, 1, 4)   # A AND B -> XOR в C (так как A*B и X*(A^B) не пересекаются по единицам)

    if measure:
        qc.measure_all()
    return qc

