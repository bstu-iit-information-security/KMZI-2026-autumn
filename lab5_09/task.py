# 4. Оптимизированная схема (8 кубитов: 4 входа, 3 ancilla с переиспользованием, 1 выход F)
# ==========================================


def build_f_optimized(
    a: int, b: int, c: int, d: int, measure: bool = True
) -> QuantumCircuit:
  """
    Кубиты:
      0..3: входы A, B, C, D (не изменяются)
      4: ancilla 1 -> сначала A OR D, после очистки q6 переиспользуется под NAND(A, C)
      5: ancilla 2 -> B OR C
      6: ancilla 3 -> (A OR D) AND (B OR C)
      7: выходной кубит F (изначально |0>)
    """
  qc = QuantumCircuit(8)
  if a:
    apply_not(qc, 0)
  if b:
    apply_not(qc, 1)
  if c:
    apply_not(qc, 2)
  if d:
    apply_not(qc, 3)

  # Отдельные подсхемы для каждого промежуточного кубита — удобно обращать через .inverse()
  or_ad_qc = QuantumCircuit(8)
  apply_or(or_ad_qc, 0, 3, 4)  # q4 = A OR D

  or_bc_qc = QuantumCircuit(8)
  apply_or(or_bc_qc, 1, 2, 5)  # q5 = B OR C

  and_12_qc = QuantumCircuit(8)
  apply_and(and_12_qc, 4, 5, 6)  # q6 = (A OR D) AND (B OR C)

  # 1. Считаем q4, q5 и q6
  qc.compose(or_ad_qc, inplace=True)
  qc.compose(or_bc_qc, inplace=True)
  qc.compose(and_12_qc, inplace=True)

  # 2. Освобождаем q5 и q4 строгим обратным ходом (.inverse()), сохраняя q6
  qc.compose(or_bc_qc.inverse(), inplace=True)
  qc.compose(or_ad_qc.inverse(), inplace=True)

  # 3. Переиспользуем освободившийся q4 под NAND(A, C) и формируем F в q7
  nand_ac_qc = QuantumCircuit(8)
  apply_nand(nand_ac_qc, 0, 2, 4)  # q4 = NAND(A, C)

  out_f_qc = QuantumCircuit(8)
  apply_and(out_f_qc, 6, 4, 7)  # q7 = q6 AND q4 = F

  qc.compose(nand_ac_qc, inplace=True)
  qc.compose(out_f_qc, inplace=True)

  # 4. Очищаем q4 и q6 обратными операциями
  qc.compose(nand_ac_qc.inverse(), inplace=True)
  # Восстанавливаем q4 и q5 только для отмены and_12_qc, затем снова обнуляем их
  qc.compose(or_ad_qc, inplace=True)
  qc.compose(or_bc_qc, inplace=True)
  qc.compose(and_12_qc.inverse(), inplace=True)
  qc.compose(or_bc_qc.inverse(), inplace=True)
  qc.compose(or_ad_qc.inverse(), inplace=True)

  if measure:
    qc.measure_all()
  return qc


